# Завдання 5. Найменше 4-значне число, яке зменшується на 27,
# якщо його останню цифру переставити на першу позицію
name = "Владислав Мельник"
puts "Привіт, #{name}!"

# 1234 -> 4123: остання цифра стає першою
def rotate(n)
  s = n.to_s
  (s[-1] + s[0..-2]).to_i
end

answer = (1000..9999).find { |n| n - rotate(n) == 27 }
puts "Шукане число: #{answer}"
puts "Перевірка: #{answer} -> #{rotate(answer)}, різниця #{answer - rotate(answer)}"
